function makeCompetitorBet(
  competitorIdx: number,
  betId: number,
  priceWithVat: number,
  place: number,
  createdAt: string,
  auctionId: number,
): BetItem {
  const c = competitor(competitorIdx)
  const vatRate = 0.2
  return {
    id: betId,
    auction_id: auctionId,
    created_at: createdAt,
    subscriber_id: c.subscriber_id,
    contact_name: c.contact_name,
    contact_phone: c.contact_phone,
    price_with_vat: priceWithVat,
    price_no_vat: Math.round((priceWithVat / (1 + vatRate)) * 100) / 100,
    organization_id: c.organization_id,
    organization_inn: c.organization_inn,
    organization_name: c.organization_name,
    is_rejected: false,
    is_counter: false,
    place,
    is_win: false,
    run_number: 0,
    cancel_reason: '',
  }
}

